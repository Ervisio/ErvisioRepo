#!/usr/bin/env bash
# Ervisio Repo Docker setup: writes .env, config/config.toml and the master
# key, then starts the stack. Safe to re-run: existing secrets are kept.
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")"

non_interactive=0
admin_email=""
url=""
ervisio=""

usage() {
  cat <<USAGE
Usage: ./setup.sh [--non-interactive] [--admin-email EMAIL] [--url PUBLIC_URL] [--ervisio yes|no]

  --non-interactive   never prompt; use flags and defaults
  --admin-email       contact address, shown in the next steps
  --url               public URL of the instance (default http://localhost:3400)
  --ervisio yes|no    yes: enable the admin socket for the Caddy plugin
USAGE
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --non-interactive) non_interactive=1 ;;
    --admin-email) admin_email="${2:?--admin-email needs a value}"; shift ;;
    --url) url="${2:?--url needs a value}"; shift ;;
    --ervisio) ervisio="${2:?--ervisio needs yes or no}"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

case "$ervisio" in ""|yes|no) ;; *) echo "--ervisio must be yes or no" >&2; exit 2 ;; esac

command -v docker >/dev/null || { echo 'Install Docker Engine / Docker Desktop and try again.' >&2; exit 1; }
docker compose version >/dev/null
docker info >/dev/null

ask() { # ask VAR PROMPT DEFAULT
  local var=$1 prompt=$2 def=$3 reply
  if [[ -n "${!var}" || $non_interactive -eq 1 || ! -t 0 ]]; then
    printf -v "$var" '%s' "${!var:-$def}"
    return
  fi
  read -r -p "$prompt [$def]: " reply
  printf -v "$var" '%s' "${reply:-$def}"
}

rand_hex() { # rand_hex BYTES
  if command -v openssl >/dev/null; then openssl rand -hex "$1"
  else head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; fi
}

ask url "Public URL" "http://localhost:3400"
ask ervisio "Enable the Caddy plugin socket (yes/no)" "no"
case "$ervisio" in yes|no) ;; *) echo "--ervisio must be yes or no" >&2; exit 2 ;; esac
url="${url%/}"
case "$url" in http://*|https://*) ;; *) echo "The URL must start with http:// or https://" >&2; exit 2 ;; esac

uid=$(id -u); gid=$(id -g)
mkdir -p config data/postgres data/repo data/runner run
chmod 700 config

# Master key: encrypts secrets at rest. Losing it makes them unrecoverable.
if [[ ! -s config/master.key ]]; then
  (umask 077; rand_hex 32 > config/master.key)
  echo 'Created config/master.key: back it up somewhere safe.'
fi
chmod 600 config/master.key

# .env: keep the database password across runs.
pg_password=""
if [[ -f .env ]]; then
  pg_password=$(sed -n 's/^POSTGRES_PASSWORD=//p' .env | head -n1)
fi
pg_password="${pg_password:-$(rand_hex 24)}"
# With the Ervisio plugin the socket must sit where the plugin looks for it.
socket_dir=./run
[[ "$ervisio" == yes ]] && socket_dir=/run/ervisio-repo
docker_gid=0
if [[ -S /var/run/docker.sock ]]; then
  docker_gid=$(stat -c %g /var/run/docker.sock 2>/dev/null || stat -f %g /var/run/docker.sock 2>/dev/null || echo 0)
fi
(umask 077; cat > .env <<ENV
POSTGRES_PASSWORD=$pg_password
ERVISIO_UID=$uid
ERVISIO_GID=$gid
ERVISIO_DATA_DIR=./data
ERVISIO_SOCKET_DIR=$socket_dir
BIND_ADDRESS=127.0.0.1
APP_PORT=3400
SSH_PORT=2222
DOCKER_GID=$docker_gid
ENV
)

plugin_socket=""
[[ "$ervisio" == yes ]] && plugin_socket="/run/ervisio-repo/api.sock"

# The first account you register becomes the instance administrator, so
# invite-only registration is safe to enable from the start.
if [[ ! -f config/config.toml ]]; then
  cat > config/config.toml <<TOML
# Generated by setup.sh. Any key can be overridden with EREPO_<SECTION>_<KEY>.
[server]
public_url = "$url"
listen = "0.0.0.0:3400"
ssh_listen = "0.0.0.0:2222"
plugin_socket = "$plugin_socket"

[security]
master_key_file = "/etc/ervisio-repo/master.key"
registration = "invite"

[log]
level = "info"
format = "json"

# Local storage on the host data directory. Add a remote target for protection
# against disk failures.
[[storage.target]]
name = "hot"
kind = "local"
path = "/var/lib/ervisio-repo/data"
budget = "50GB"

[storage.policy.git]
primary = "hot"
TOML
  echo 'Created config/config.toml.'
else
  echo 'Kept the existing config/config.toml.'
fi
chmod 640 config/config.toml 2>/dev/null || true

# Use the published image; if it cannot be pulled, compose builds it locally.
docker compose pull --ignore-pull-failures --quiet
docker compose up -d --wait --wait-timeout 300

echo
echo "Ervisio Repo is running at $url"
echo "  1. Open the URL and register: the first account becomes the administrator."
[[ -n "$admin_email" ]] && echo "     Use $admin_email for that account."
echo "  2. Behind Caddy: ervisio-repo caddy setup --host <your-domain> (see docs/install.md)."
echo "  3. Stop with: docker compose stop. Optional: --profile runner, --profile backup."
